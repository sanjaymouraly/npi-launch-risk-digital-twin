def task(ref, code, name, phase, duration, resources, cost, **kw):
    row = {
        "ref": ref, "code": code, "name": name, "phase": phase,
        "duration_days": duration, "resources": resources, "cost": cost,
    }
    row.update(kw)
    return row


def dep(a, b, typ="FS", lag=0):
    return {"from": a, "to": b, "type": typ, "lag_days": lag}


